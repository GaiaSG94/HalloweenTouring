#!/usr/bin/env python3
"""Assemble parts/ into a single self-contained index.html (GENERATED)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PARTS = ROOT / "parts"
HEADER = "<!-- GENERATED by build.py from parts/ -- do not edit by hand. -->\n"


def build_text():
    files = sorted((p for p in PARTS.iterdir() if p.is_file()), key=lambda p: p.name)
    chunks = [HEADER]
    for path in files:
        text = path.read_text(encoding="utf-8")
        if not text.endswith("\n"):
            text += "\n"
        chunks.append(text)
    return "".join(chunks), [p.name for p in files]


def main(argv):
    check = "--check" in argv
    out = ROOT / "index.html"
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1])
    text, names = build_text()
    if check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"OUT OF SYNC: {out} differs from parts/ ({len(names)} parts)")
            return 1
        print(f"OK: {out} matches parts/ ({len(names)} parts)")
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text)} bytes, {len(names)} parts)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
